/** Источник сведений, на которых основано содержание документа. */
export interface DocumentSource {
  /** Адрес, путь или явно названный источник сообщения. */
  location: string;
  /** Дословный фрагмент источника, если он доступен. */
  quote?: string;
}

/** Продукт и граница его ответственности. */
export interface Product {
  /** Уникальный идентификатор документа в проверяемом наборе. */
  id: string;
  /** Признак документа продукта. */
  type: 'product';
  /** Краткое содержательное название. */
  name: string;
  /** Краткое описание для каталога и поиска. */
  summary?: string;
  /** Точные имена групп для поиска; они не являются ссылками на документы. */
  group?: string[];
  /** Источники сведений о продукте. */
  sources?: DocumentSource[];
  /** Явно неизвестные факты и открытые вопросы. */
  gaps?: string[];
  /** Для чего существует продукт. */
  purpose: string;
  /** Что входит в продукт и где заканчивается его ответственность. */
  boundary: string;
}

/** Пользовательская цель и польза от её достижения. */
export interface UserStory {
  /** Уникальный идентификатор документа в проверяемом наборе. */
  id: string;
  /** Признак пользовательской истории. */
  type: 'user-story';
  /** Краткое содержательное название. */
  name: string;
  /** Краткое описание для каталога и поиска. */
  summary?: string;
  /** Точные имена групп для поиска; они не являются ссылками на документы. */
  group?: string[];
  /** Источники сведений о пользовательской цели. */
  sources?: DocumentSource[];
  /** Явно неизвестные факты и открытые вопросы. */
  gaps?: string[];
  /** Идентификатор продукта, к которому относится история. */
  product_ref: string;
  /** Роль пользователя в содержательной формулировке, без ссылки на отдельный документ. */
  actor: string;
  /** Чего эта роль хочет достичь. */
  goal: string;
  /** Для чего достижение цели нужно этой роли. */
  benefit: string;
}

/** Наблюдаемое поведение продукта и условия его приёмки. */
export interface FunctionalRequirement {
  /** Уникальный идентификатор документа в проверяемом наборе. */
  id: string;
  /** Признак функционального требования. */
  type: 'functional-requirement';
  /** Краткое содержательное название. */
  name: string;
  /** Краткое описание для каталога и поиска. */
  summary?: string;
  /** Точные имена групп для поиска; они не являются ссылками на документы. */
  group?: string[];
  /** Источники сведений о требуемом поведении. */
  sources?: DocumentSource[];
  /** Явно неизвестные факты и открытые вопросы. */
  gaps?: string[];
  /** Идентификатор продукта, к которому относится требование. */
  product_ref: string;
  /** Одно проверяемое поведение продукта. */
  statement: string;
  /** Условие или событие, вызывающее поведение. */
  trigger?: string;
  /** Идентификаторы пользовательских историй, обосновывающих требование. */
  story_refs?: string[];
  /** Идентификаторы нефункциональных требований, ограничивающих поведение. */
  constraint_refs?: string[];
  /** Наблюдаемые условия выполнения требования; список должен быть непустым. */
  acceptance_criteria: string[];
}

/** Допустимая категория нефункционального свойства продукта. */
export type NonFunctionalRequirementKind =
  | 'performance'
  | 'reliability'
  | 'security'
  | 'usability'
  | 'maintainability'
  | 'compatibility'
  | 'other';

/** Измеримое свойство или ограничение продукта. */
export interface NonFunctionalRequirement {
  /** Уникальный идентификатор документа в проверяемом наборе. */
  id: string;
  /** Признак нефункционального требования. */
  type: 'non-functional-requirement';
  /** Краткое содержательное название. */
  name: string;
  /** Краткое описание для каталога и поиска. */
  summary?: string;
  /** Точные имена групп для поиска; они не являются ссылками на документы. */
  group?: string[];
  /** Источники сведений о требуемом свойстве. */
  sources?: DocumentSource[];
  /** Явно неизвестные факты и открытые вопросы. */
  gaps?: string[];
  /** Идентификатор продукта, к которому относится требование. */
  product_ref: string;
  /** Категория свойства из закрытого набора значений. */
  kind: NonFunctionalRequirementKind;
  /** Какое свойство требуется от продукта. */
  statement: string;
  /** Как измеряют требуемое свойство. */
  measure: string;
  /** Целевое значение с единицами измерения, когда они применимы. */
  target: string;
  /** Условия и область, для которых задано целевое значение. */
  context: string;
}

/** Один из четырёх продуктовых документов первого цикла. */
export type ProductDocument = Product | UserStory | FunctionalRequirement | NonFunctionalRequirement;
