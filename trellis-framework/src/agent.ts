/** Вход первой задачи сбора продуктовых требований. */
export interface TaskInput {
  /** Запрос человека; существующие документы агент читает из рабочей копии. */
  request: string;
}

/** Возможные исходы попытки внешнего исполнителя. */
export type TaskStatus = 'completed' | 'needs_input' | 'failed';

/** Отчёт исполнителя; сам по себе не подтверждает прохождение гейтов. */
export interface TaskResult {
  /** Заявленный исход попытки, не результат проверки Git-артефактов. */
  status: TaskStatus;
  /** Краткое резюме работы или причины остановки; документы остаются в Git. */
  summary: string;
}
